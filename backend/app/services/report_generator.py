"""
TrustShield AI — Cyber Resilience Backend
Report Generator Service

Builds a structured, timestamped investigation report from a scan result.
"""

import uuid
from datetime import datetime, timezone
from typing import Dict, Any


class ReportGenerator:
    """
    Generates a structured JSON report from a scan result.
    """

    @staticmethod
    def generate(scan_type: str, scan_data: Dict[str, Any], user_notes: str = None) -> Dict[str, Any]:
        """
        Build a comprehensive report.
        """
        report_id = f"TS-{uuid.uuid4().hex[:8].upper()}"
        generated_at = datetime.now(timezone.utc).isoformat()

        # Extract core fields safely
        risk_label = scan_data.get("label", "UNKNOWN")
        risk_score = scan_data.get("score", 0.0)
        indicators = scan_data.get("evidence", [])
        threat_intel = scan_data.get("threat_intelligence", [])
        recommendations = scan_data.get("recommendations", [])

        # Build a summary of indicators
        indicator_summary = [
            {
                "code": ind.get("code", "UNKNOWN"),
                "description": ind.get("description", ""),
                "risk_contribution": ind.get("risk_contribution", ""),
                "matched_text": ind.get("matched_text", ""),
            }
            for ind in indicators
        ]

        # Build threat intel summary
        ti_summary = [
            {
                "source": ti.get("source", "Unknown"),
                "found": ti.get("found", False),
                "status": ti.get("status", ""),
                "error": ti.get("error", ""),
            }
            for ti in threat_intel
        ]

        report = {
            "report_id": report_id,
            "generated_at": generated_at,
            "scan_type": scan_type.upper(),
            "summary": {
                "risk_label": risk_label,
                "risk_score": risk_score,
                "indicator_count": len(indicators),
                "threat_intel_sources": len(threat_intel),
            },
            "input": scan_data.get("url_analysed") or scan_data.get("message_preview", ""),
            "indicators": indicator_summary,
            "threat_intelligence": ti_summary,
            "recommendations": recommendations,
            "user_notes": user_notes or "",
            "disclaimer": (
                "This report is generated by TrustShield AI Cyber Resilience module. "
                "It is based on rule-based heuristics and optional threat-intelligence lookups. "
                "It does not constitute a legal or forensic investigation."
            ),
        }

        return report